// export_theri_parts_v2.js v1.2 (Mecha Dino Arena) — exports the 7 picked Therizino part looks from the redesign mockup
// (docs/mockups/therizino_parts_redesign.html v0.5; Kepu 2026-11-04 14:49 final picks) to src/shared/TheriPartsLooksV2.luau.
// Plan docs/plans/THERIZINO_PARTS_LOOKS_v2.0.md Task 1 (MDA-249). Run: node tools/mockup/export_theri_parts_v2.js
// (rebuild the page first: python3 tools/mockup/build_therizino_parts_v2.py). Uses the preinstalled Playwright Chromium.
// Every piece is taken at rest (use = 0, t = 0): offset = anchor rest CF^-1 x piece rest CF (Roblox CFrame components; the
// mockup uses Roblox's axes). Pieces hidden at rest are skipped, except see-through "film" pieces (kept, shown by
// TheriPartsAnim). Groups: pivot (anchor-relative), motion, parent. Beams: the mockup's cables.
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
// v1.1: Kepu 2026-11-04 14:49 final picks: Hook-B Reaper Crane, Feathers-A, Harvest-B Reaper Sleeves (claws + wrist cuffs only),
// Grapple-B, Deflect-B Mane Rotor, Overclock-A, Snare-A (no two parts on one forearm).
// v1.2: moves rework (plan docs/plans/THERIZINO_MOVES_REWORK_v1.0.md, MDA-261): hook -> Reaper Launcher (chest, look 2),
// grapple -> Storm Core (look 3, the dash part).
const PICKS = [["hook", 2, "zhook"], ["feather", 0, "zfeather"], ["harvest", 1, "zharvest"], ["grapple", 3, "zgrapple"], ["deflect", 1, "zdeflect"], ["overclock", 0, "zclock"], ["snare", 0, "zsnare"]];
(async () => {
  const b = await chromium.launch({args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist']});
  const p = await b.newPage();
  const errs = []; p.on('pageerror', e => errs.push(String(e)));
  await p.goto('file://' + path.join(ROOT, 'docs', 'mockups', 'therizino_parts_redesign.html'));
  await p.waitForTimeout(600);
  const out = await p.evaluate((PICKS) => {
    const r4 = v => Math.round(v * 10000) / 10000;
    // position (3 decimals) + XYZ Euler degrees (2 decimals): three's "XYZ" = Rx * Ry * Rz = Roblox CFrame.Angles(rx, ry, rz)
    const comps = m => { const p = new THREE.Vector3().setFromMatrixPosition(m), e = new THREE.Euler().setFromRotationMatrix(m, "XYZ"), d = THREE.MathUtils.radToDeg;
      const r3 = v => Math.round(v * 1000) / 1000, r2 = v => Math.round(v * 100) / 100 + 0; return [r3(p.x), r3(p.y), r3(p.z), r2(d(e.x)), r2(d(e.y)), r2(d(e.z))].map(v => Object.is(v, -0) ? 0 : v); };
    const res = {};
    for (const [pid, li, gid] of PICKS) {
      cur = PARTS.findIndex(x => x.id === pid); look = li; old = false; use = 0; t = 0; build();
      // mounts: distinct (anchor, mount frame) pairs; pieces and group pivots are given in their mount's frame
      const mounts = [], mkey = [];
      const mountOf = (part, mo) => { const k = part + ':' + comps(mo).join(','); let i = mkey.indexOf(k); if (i < 0) { mkey.push(k); mounts.push({anchor: part, frame: comps(mo)}); i = mounts.length - 1; } return i + 1; };
      const pieces = [];
      for (const e of equip) {
        const film = !!e.film;
        if (e.show && !e.show(0, 0) && !film) continue;
        const local = e.place ? e.place(0, 0) : e.mountOff.clone().invert().multiply(e.off);
        pieces.push({mount: mountOf(e.part, e.mountOff), anchor: e.part, shape: e.sh, size: e.s.slice(0, 3).map(v => Math.round((v || 0) * 1000) / 1000), off: comps(local), mat: e.key, role: e.role || null, group: e.group || null, detail: !!e.detail, film});
      }
      const groups = GROUPS.map(g => ({name: g.name, mount: mountOf(g.part, g.mountOff), anchor: g.part, pivot: comps(g.local), type: g.motion.type, axis: g.motion.axis, amt: r4(g.motion.amt), parent: g.parent || null}));
      const beams = cables.map(c => {
        const ia = theri.byName[c.pa].cf.clone().invert(), ib = theri.byName[c.pb].cf.clone().invert();
        return {a0: c.pa, p0: new THREE.Vector3(...c.a).applyMatrix4(ia).toArray().map(v => Math.round(v * 1000) / 1000), a1: c.pb, p1: new THREE.Vector3(...c.b).applyMatrix4(ib).toArray().map(v => Math.round(v * 1000) / 1000), width: r4(c.d)};
      });
      res[gid] = {look: PARTS[cur].looks[li].name, glow: AREA[PARTS[cur].area][2], mounts, pieces, groups, beams};
    }
    return res;
  }, PICKS);
  await b.close();
  if (errs.length) { console.error(errs); process.exit(1); }
  // ---- Luau ----
  const q = s => s === null ? 'nil' : JSON.stringify(s);
  const arr = a => '{' + a.join(', ') + '}';
  let L = `-- TheriPartsLooksV2 v1.2 (Mecha Dino Arena) — GENERATED by tools/mockup/export_theri_parts_v2.js from
-- docs/mockups/therizino_parts_redesign.html v0.5 (Kepu 2026-11-04 14:49 picks: Hook-B Reaper Crane, Feathers-A Blade
-- Wings, Harvest-B Reaper Sleeves (claws + wrist cuffs), Grapple-B Belly Winch, Deflect-B Mane Rotor, Overclock-A Piston Legs,
-- Snare-A Tail Spool Rig; no two parts on one forearm). Plan docs/plans/THERIZINO_PARTS_LOOKS_v2.0.md Task 1 (MDA-249).
-- v1.2 (moves rework, plan docs/plans/THERIZINO_MOVES_REWORK_v1.0.md, MDA-261): zhook = Reaper Launcher (chest), zgrapple =
-- Storm Core (belly capacitor + shoulder coils; roles core / hornL / hornR), from the moves storyboard v0.3. Do not edit by hand: change the mockup, re-export.
-- ServerStorage.DinoArcade.TheriPartsLooksV2 (ModuleScript). Scale 1 (the server multiplies positions and sizes by the
-- model's scale). LOOKS[id] = {look, glow (Color3), pieces, groups, beams}:
-- A frame below = x, y, z, rx, ry, rz: CFrame.new(x, y, z) * CFrame.Angles(rad rx, rad ry, rad rz).
--   mount = {anchor (TherizinoModelData part), frame (relative to the anchor's rest frame)}
--   piece (flat row) = {mount (index), shape ("box" | "wedge" | "cyl" | "ball" | "cone" | "ring"), sx, sy, sz (cyl: diameter,
--     length along the piece's Y (the mockup's axis), 0; cone: base diameter, height (tip +Y), 0; ring: radius, tube, 0, a
--     torus around the piece's Z axis), frame (6 numbers, in the
--     mount's frame), mat (kit key), role ("" = none), group ("" = none), flags (1 = detail (dropped by "lite"), 2 = film
--     (see-through, shown only while the move plays))}
--   group (flat row) = {name, mount (index), frame (6 numbers: the pivot, in the mount's frame), type ("spin" | "swing" |
--     "slide"), axis ("X" | "Y" | "Z", in the pivot frame), amt (spin: rad/s; swing: degrees at full; slide: studs at full,
--     x scale), parent ("" = none)}
--   beam = {a0, p0, a1, p1 (anchor-relative positions), width}
-- The camera side is +X = the model's "...L" parts (ShoulderCam 1.8 over the right shoulder; L / R names are mirrored).
local M = {}
M.Version = "1.2"
M.KIT = {shell = {0x5a636f, "stud"}, plate = {0x828c99, "stud"}, trim = {0x26292f, "plain"}, bone = {0xe2dccb, "plain"},
	ivory = {0xcfc6ae, "stud"}, brass = {0xc9a24a, "metal"}, steel = {0x9aa3ad, "metal"}, iron = {0x5d636c, "metal"},
	rubber = {0x16171b, "plain"}, hazY = {0xffc832, "plain"}, hazK = {0x1a1a1a, "plain"}, glow = {0, "neon"}, white = {0xf4f8ff, "neon"}}
M.LOOKS = {}
`;
  for (const [, , gid] of PICKS) {
    const d = out[gid];
    L += `M.LOOKS.${gid} = {look = ${q(d.look)}, glow = Color3.fromRGB(${(d.glow >> 16) & 255}, ${(d.glow >> 8) & 255}, ${d.glow & 255}),\nmounts = {\n`;
    for (const mt of d.mounts) L += `{${q(mt.anchor)}, ${mt.frame.join(', ')}},\n`;
    L += `},\npieces = {\n`;
    for (const pc of d.pieces) L += `{${pc.mount}, ${q(pc.shape)}, ${pc.size.join(', ')}, ${pc.off.join(', ')}, ${q(pc.mat)}, ${q(pc.role || '')}, ${q(pc.group || '')}, ${(pc.detail ? 1 : 0) + (pc.film ? 2 : 0)}},\n`;
    L += `},\ngroups = {\n`;
    for (const g of d.groups) L += `{${q(g.name)}, ${g.mount}, ${g.pivot.join(', ')}, ${q(g.type)}, ${q(g.axis)}, ${g.amt}, ${q(g.parent || '')}},\n`;
    L += `},\nbeams = {\n`;
    for (const bm of d.beams) L += `{a0 = ${q(bm.a0)}, p0 = ${arr(bm.p0)}, a1 = ${q(bm.a1)}, p1 = ${arr(bm.p1)}, width = ${bm.width}},\n`;
    L += `},\n}\n`;
  }
  L += `return M\n`;
  const file = path.join(ROOT, 'src', 'shared', 'TheriPartsLooksV2.luau');
  fs.writeFileSync(file, L);
  for (const [, , gid] of PICKS) { const d = out[gid]; console.log(gid, d.look, 'mounts', d.mounts.length, 'pieces', d.pieces.length, 'detail', d.pieces.filter(x => x.detail).length, 'groups', d.groups.length, 'beams', d.beams.length); }
})();
