// export_troodon_parts.js v1.0 (Mecha Dino Arena) — exports the 9 recommended Troodon part looks from the looks + moves mockup
// (docs/mockups/troodon_parts_options.html v0.2, tools/mockup/troodon_parts_looks.js; Kepu 2026-11-06 21:24 "I like all the
// recommended") to src/shared/TrooPartsLooks.luau. Plan docs/plans/TROODON_PARTS_v1.0.md ticket 3 (MDA-347).
// Run: node tools/mockup/export_troodon_parts.js (rebuild the page first if the mockup changed:
// python3 tools/mockup/build_troodon_parts_looks.py). Uses the preinstalled Playwright Chromium.
// Every piece is taken at rest (msReset, variant "R" = the recommended look of each part): frame = the segment root's rest
// CFrame^-1 x the piece's rest model-space matrix x its geometry matrix, scale split off (only the scaled spheres carry one).
// The mockup's model space is TroodonModelData's rest space at scale 1 with Roblox's axes (cfm reads the 12 CFrame numbers
// row by row), the same mapping as DiloPartsServer.
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
// mockup part id -> SkillTree path id
const IDS = {mender: "omender", lantern: "olantern", sapwall: "osapwall", shed: "oshed", portal: "oportal",
  lastfeather: "olastfeather", plume: "oplume", fortify: "ofortify", ricochet: "oricochet"};
(async () => {
  const b = await chromium.launch({args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist']});
  const p = await b.newPage();
  const errs = []; p.on('pageerror', e => errs.push(String(e)));
  await p.goto('file://' + path.join(ROOT, 'docs', 'mockups', 'troodon_parts_options.html'));
  await p.waitForTimeout(800);
  const out = await p.evaluate(() => {
    window.__manual = true;
    lookOverride = new Set(Object.keys(REC).map(k => k + "." + REC[k])); msReset(); mechLocals();
    const r4 = v => { const x = Math.round(v * 1000) / 1000; return Object.is(x, -0) ? 0 : x; };
    const matKey = m => { for (const k in MAT) if (MAT[k] === m) return k; for (const k in PMAT) if (PMAT[k] === m) return k.split(".")[1]; return "gun"; };
    const res = {};
    for (const pid in REC) {
      const look = pid + "." + REC[pid];
      const mk = MK[look] || {};
      const carries = mk.carries || (mk.carry ? [mk.carry] : []);
      const pieces = [];
      for (const pc of MECH) {
        if (pc.look !== look || !pc.mesh.visible) continue;
        const sh = pc.mesh.geometry.userData.shape;
        const M = pc.local.clone().multiply(pc.mesh.geometry.userData.M);
        const pos = new THREE.Vector3(), q = new THREE.Quaternion(), s = new THREE.Vector3();
        M.decompose(pos, q, s);
        const R = new THREE.Matrix4().makeRotationFromQuaternion(q), e = R.elements;
        let role = "";
        const ci = carries.findIndex(c => c.pieces.includes(pc));
        if (ci >= 0) role = carries.length > 1 ? "carry" + (ci + 1) : "carry";
        else if (mk.shed && mk.shed.includes(pc)) role = "shed";
        else if (pc.bracket) role = "bracket";
        let anim = "";
        if (pc.anim) { const src = String(pc.anim); const m = src.match(/MS\.([a-zA-Z]+)/); anim = m ? m[1] : "anim"; }
        const mat = matKey(pc.mesh.material);
        const glow = !!(pc.mesh.material.userData && pc.mesh.material.userData.part);
        let dims;
        if (sh.t === "box") dims = [sh.w, sh.h, sh.d, 0];
        else if (sh.t === "cyl") dims = [sh.r1, sh.r2, sh.h, (pc.mesh.geometry.parameters && pc.mesh.geometry.parameters.radialSegments) || 16];
        else if (sh.t === "sph") dims = [sh.r, 0, 0, 0];
        else dims = [sh.R, sh.r, sh.arc, 0];
        pieces.push({seg: pc.seg, t: sh.t, dims: dims.map(r4), cf: [pos.x, pos.y, pos.z, e[0], e[4], e[8], e[1], e[5], e[9], e[2], e[6], e[10]].map(r4),
          scale: [s.x, s.y, s.z].map(r4), mat, glow, role, anim, name: pc.name});
      }
      const marks = carries.map((c, i) => { const v = new THREE.Vector3().setFromMatrixPosition(segInv[c.seg].clone().multiply(c.F)); return {name: carries.length > 1 ? "carry" + (i + 1) : "carry", seg: c.seg, p: [v.x, v.y, v.z].map(r4)}; });
      if (mk.c) { const segName = pieces.length ? pieces[pieces.length - 1].seg : "Torso"; const v = mk.c.clone().applyMatrix4(segInv[segName]); marks.push({name: "centre", seg: segName, p: [v.x, v.y, v.z].map(r4)}); }
      res[pid] = {look: LOOKS[pid][REC[pid]].name, mount: LOOKS[pid][REC[pid]].mount, letter: REC[pid], pieces, marks};
    }
    return res;
  });
  await b.close();
  if (errs.length) { console.error(errs); process.exit(1); }
  const q = s => JSON.stringify(s);
  let L = `-- TrooPartsLooks v1.0 (Mecha Dino Arena) — GENERATED by tools/mockup/export_troodon_parts.js from
-- docs/mockups/troodon_parts_options.html v0.2 (tools/mockup/troodon_parts_looks.js; Kepu 2026-11-06 21:24 "I like all the
-- recommended"): Mender Drone A Shoulder Dock, Arc Lantern A Hip Lantern, Sap Wall B Shoulder Pod, Feather Shed A Flank Plates,
-- Portal Feathers A Tail Rings, Last Feather A Tail-Base Cell, Overheal Plume A Tail Plume, Fortify Field B Neck Pylon, Ricochet
-- Pod A Spring Cups. Plan docs/plans/TROODON_PARTS_v1.0.md ticket 3 (MDA-347). Do not edit by hand: change the mockup, re-export.
-- ServerStorage.DinoArcade.TrooPartsLooks (ModuleScript). Scale 1, TroodonModelData rest space (TrooPartsServer multiplies
-- positions and sizes by the model's scale). LOOKS[pathId] = {look, mount, pieces, marks}:
--   piece (flat row) = {seg (TroodonModelData segment; the piece rides its Root), t ("box" | "cyl" | "sph" | "tor"), d1, d2,
--     d3, d4, then 12 numbers: the CFrame relative to the segment root's rest CFrame (x, y, z, R00 .. R22; the shape's own
--     frame), sx, sy, sz (scale; spheres only), mat (MAT key or glow key), glow (1 = the part's own glow material), role ("" |
--     "carry" | "carry1" | "carry2" | "shed" | "bracket"), anim ("" | "spin" | "open" | "spring": the mockup's moving pieces)}
--     box: d1..d3 = width (X), height (Y), depth (Z); cyl: d1 = radius at +Y, d2 = radius at -Y, d3 = length along Y, d4 = sides;
--     sph: d1 = radius (x sx / sy / sz); tor: d1 = ring radius, d2 = tube radius, d3 = arc (radians), in the XY plane (axis Z).
--   mark (flat row) = {name ("carry" | "carry1" | "carry2" | "centre"), seg, x, y, z (relative to the segment root's rest CFrame)}
local M = {}
M.Version = "1.0"
M.LOOKS = {}
`;
  for (const pid in IDS) {
    const d = out[pid];
    L += `M.LOOKS.${IDS[pid]} = {look = ${q(d.look)}, mount = ${q(d.mount)},\npieces = {\n`;
    for (const pc of d.pieces) L += `{${q(pc.seg)},${q(pc.t)},${pc.dims.join(',')},${pc.cf.join(',')},${pc.scale.join(',')},${q(pc.mat)},${pc.glow ? 1 : 0},${q(pc.role)},${q(pc.anim)}},\n`;
    L += `},\nmarks = {\n`;
    for (const mk of d.marks) L += `{${q(mk.name)},${q(mk.seg)},${mk.p.join(',')}},\n`;
    L += `},\n}\n`;
  }
  L += `return M\n`;
  const file = path.join(ROOT, 'src', 'shared', 'TrooPartsLooks.luau');
  fs.writeFileSync(file, L);
  for (const pid in IDS) { const d = out[pid]; console.log(IDS[pid], d.letter, d.look, '|', d.mount, '| pieces', d.pieces.length, 'brackets', d.pieces.filter(x => x.role === 'bracket').length, 'marks', d.marks.map(m => m.name).join('/'), 'scaled', d.pieces.filter(x => x.scale.some(v => Math.abs(v - 1) > 1e-3)).length); }
})();
