// export_looks.js v1.0 (Mecha Dino Arena) — exports the 5 Troodon slot-part looks (Bloom Tank, Bloom Burst, Shield Dome, Sleep
// Dart, Sentry Pod) from docs/mockups/troodon_slotparts_v0.1.html (tools/troodon_slotparts_mockup/slotparts.js; Kepu 2026-11-10
// 01:40 picks, 09:46 "Then build") to src/shared/TrooSlotLooks.luau, in TrooPartsLooks 1.0's row format (same maths as
// tools/mockup/export_troodon_parts.js). Run: node tools/troodon_slotparts_mockup/export_looks.js (after build.py).
// Differences from export_troodon_parts.js: carried pieces are found through piece.carry (makeCarry), the piece anims read the
// page's NS fields (NS.fill / NS.sentLeg / NS.sentYaw / NS.sleepKick -> anim "fill" / "sentLeg" / ...), and a see-through
// material (the Bloom Tank's glass) exports as "glassT".
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const IDS = {bloom: "obloom", burst: "oburst", dome: "odome", sleep: "osleep", sentry: "osentry"};
(async () => {
  const b = await chromium.launch({args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist']});
  const p = await b.newPage();
  await p.route(/fonts\.(googleapis|gstatic)\.com/, r => r.abort());
  const errs = []; p.on('pageerror', e => errs.push(String(e)));
  await p.goto('file://' + path.join(ROOT, 'docs', 'mockups', 'troodon_slotparts_v0.1.html'));
  await p.waitForFunction(() => window.__ready, null, {timeout: 60000});
  const out = await p.evaluate((IDS) => {
    lookOverride = new Set(Object.keys(IDS).map(k => k + ".A")); nsReset(); mechLocals();
    const r4 = v => { const x = Math.round(v * 1000) / 1000; return Object.is(x, -0) ? 0 : x; };
    const matKey = m => { for (const k in MAT) if (MAT[k] === m) return k; for (const k in PMAT) if (PMAT[k] === m) return k.split(".")[1]; if (m.transparent && m.opacity < 1) return "glassT"; return "gun"; };
    const res = {};
    for (const pid in IDS) {
      const look = pid + ".A";
      const carries = [];
      const pieces = [];
      for (const pc of MECH) {
        if (pc.look !== look) continue;
        const sh = pc.mesh.geometry.userData.shape;
        const M = pc.local.clone().multiply(pc.mesh.geometry.userData.M);
        const pos = new THREE.Vector3(), q = new THREE.Quaternion(), s = new THREE.Vector3();
        M.decompose(pos, q, s);
        const R = new THREE.Matrix4().makeRotationFromQuaternion(q), e = R.elements;
        let role = "";
        if (pc.carry) { if (!carries.includes(pc.carry)) carries.push(pc.carry); role = "carry"; }
        else if (pc.bracket) role = "bracket";
        let anim = "";
        if (pc.anim) { const src = String(pc.anim); const m = src.match(/(?:MS|NS)\.([a-zA-Z]+)/); anim = m ? m[1] : "anim"; }
        const mat = matKey(pc.mesh.material);
        const glow = !!(pc.mesh.material.userData && pc.mesh.material.userData.part);
        let dims;
        if (sh.t === "box") dims = [sh.w, sh.h, sh.d, 0];
        else if (sh.t === "cyl") dims = [sh.r1, sh.r2, sh.h, (pc.mesh.geometry.parameters && pc.mesh.geometry.parameters.radialSegments) || 16];
        else if (sh.t === "sph") dims = [sh.r, 0, 0, 0];
        else dims = [sh.R, sh.r, sh.arc, 0];
        pieces.push({seg: pc.seg, t: sh.t, dims: dims.map(r4), cf: [pos.x, pos.y, pos.z, e[0], e[4], e[8], e[1], e[5], e[9], e[2], e[6], e[10]].map(r4),
          scale: [s.x, s.y, s.z].map(r4), mat, glow, role, anim});
      }
      const marks = carries.map(c => { const v = new THREE.Vector3().setFromMatrixPosition(segInv[c.seg].clone().multiply(c.F)); return {name: "carry", seg: c.seg, p: [v.x, v.y, v.z].map(r4)}; });
      const cand = CANDS.find(c => c.id === pid);
      res[pid] = {look: "A · " + cand.name, mount: SPOT[pid], pieces, marks};
    }
    return res;
  }, IDS);
  await b.close();
  if (errs.length) { console.error(errs); process.exit(1); }
  const q = s => JSON.stringify(s);
  let L = `-- TrooSlotLooks v1.0 (Mecha Dino Arena) — GENERATED by tools/troodon_slotparts_mockup/export_looks.js from
-- docs/mockups/troodon_slotparts_v0.1.html (Kepu 2026-11-10 01:40 picks, 09:46 "Then build"): Bloom Tank (passive), Bloom Burst,
-- Shield Dome, Sleep Dart, Sentry Pod. Plan docs/plans/TROODON_SLOTPARTS_v1.0.md. Do not edit by hand: change the mockup, re-export.
-- ServerStorage.DinoArcade.TrooSlotLooks (ModuleScript), read by TrooPartsServer 1.2. Same format as TrooPartsLooks 1.0: scale 1,
-- TroodonModelData rest space; LOOKS[pathId] = {look, mount, pieces, marks}; piece rows {seg, t, d1..d4, 12 CFrame numbers
-- relative to the segment root's rest CFrame, sx, sy, sz, mat, glow, role ("" | "carry" | "bracket"), anim ("" | the mockup's
-- moving field: fill / sentLeg / sentYaw / sleepKick)}; mark rows {name, seg, x, y, z}. Extra material key: "glassT" (the tank).
local M = {}
M.Version = "1.0"
M.LOOKS = {}
`;
  for (const pid in IDS) {
    const d = out[pid];
    L += `M.LOOKS.${IDS[pid]} = {look = ${q(d.look)}, mount = ${q(d.mount)},\npieces = {\n`;
    for (const pc of d.pieces) L += `{${q(pc.seg)},${q(pc.t)},${pc.dims.join(',')},${pc.cf.join(',')},${pc.scale.join(',')},${q(pc.mat)},${pc.glow ? 1 : 0},${q(pc.role)},${q(pc.anim)}},\n`;
    L += `},\nmarks = {\n`;
    for (const mk of d.marks) L += `{${q(mk.name)},${q(mk.seg)},${mk.p.join(',')}},\n`;
    L += `},\n}\n`;
  }
  L += `return M\n`;
  fs.writeFileSync(path.join(ROOT, 'src', 'shared', 'TrooSlotLooks.luau'), L);
  for (const pid in IDS) { const d = out[pid]; console.log(IDS[pid], d.look, '| pieces', d.pieces.length, 'brackets', d.pieces.filter(x => x.role === 'bracket').length, 'carry', d.pieces.filter(x => x.role === 'carry').length, 'mats', [...new Set(d.pieces.map(x => x.mat))].join('/'), 'anims', [...new Set(d.pieces.map(x => x.anim).filter(Boolean))].join('/'), 'segs', [...new Set(d.pieces.map(x => x.seg))].join('/')); }
})();
